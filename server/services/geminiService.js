const MODELS = [
  'gemini-3.5-flash',
  'gemini-3.8-flash',
  'gemini-flash-latest'
];

/**
 * Call Google Gemini API to answer user queries with full CRM context
 */
async function askGemini({ message, history = [], currentView = 'dashboard', userRole = 'specialist', userName = 'Сотрудник' }) {
  if (!GEMINI_API_KEY) {
    throw new Error('Ключ GEMINI_API_KEY не настроен на сервере');
  }

  // Build context-aware prompt
  const viewDescriptions = {
    dashboard: 'Главная панель управления (сводка показателей, выручка, расписание на сегодня)',
    schedule: 'Интерактивное расписание (сетка слотов по специалистам, создание и перенос занятий)',
    children: 'Карточки детей (медицинский контроль, аллергии, астма, эпилепсия, контакты родителей)',
    specialists: 'Управление специалистами (добавление, удаление в 1 клик, ставки, направления)',
    attendance: 'Табель посещаемости (отметка сессий, статус присутствия)',
    accounting: 'Интеллектуальная бухгалтерия (сплит 50/50, финансовые транзакции, выручка)',
    payroll: 'Заработная плата (начисления специалистам, ведомость выплат)',
    users: 'Сотрудники и Заявки (модерация регистраций, права доступа)',
    audit: 'Журнал аудита (протокол действий системы)',
    profile: 'Личный профиль сотрудника'
  };

  const contextNote = `[Контекст пользователя: Имя: ${userName}, Роль: ${userRole}, Текущий открытый раздел сайта: ${viewDescriptions[currentView] || currentView}]`;

  // Format history for Gemini
  const contents = [];
  
  // Add previous messages (up to last 6 for brevity and speed)
  const recentHistory = Array.isArray(history) ? history.slice(-6) : [];
  for (const h of recentHistory) {
    if (h.role === 'user') {
      contents.push({ role: 'user', parts: [{ text: h.text || h.content || '' }] });
    } else if (h.role === 'model' || h.role === 'assistant') {
      contents.push({ role: 'model', parts: [{ text: h.text || h.content || '' }] });
    }
  }

  // Add current message with context
  contents.push({
    role: 'user',
    parts: [{ text: `${contextNote}\n\nВопрос пользователя: ${message}` }]
  });

  let lastError = null;

  for (const model of MODELS) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GEMINI_API_KEY}`;
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: SYSTEM_INSTRUCTION }]
          },
          contents,
          generationConfig: {
            temperature: 0.4,
            maxOutputTokens: 1024,
            topP: 0.8
          }
        })
      });

      if (!response.ok) {
        const errText = await response.text();
        console.warn(`[Gemini API Warning] Model ${model} returned ${response.status}:`, errText.slice(0, 100));
        lastError = new Error(`Gemini ${model} HTTP ${response.status}`);
        continue;
      }

      const data = await response.json();
      const reply = data?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (reply && reply.trim()) {
        return {
          reply: reply.trim(),
          modelUsed: model
        };
      }
    } catch (err) {
      console.warn(`[Gemini API Error] Model ${model}:`, err.message);
      lastError = err;
    }
  }

  throw lastError || new Error('Не удалось получить ответ от Gemini API');
}

module.exports = {
  askGemini,
  SYSTEM_INSTRUCTION
};
